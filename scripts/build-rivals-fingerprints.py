"""Build compact color summaries from original-card images in a local directory.

Use numeric PNG filenames for the DQRDB catalog and FT-ID JPG filenames for supplementary references.
Only the color summaries are written to the game; source images stay in the input directory.
"""
import argparse
from base64 import b64encode, b64decode
import json
import re
from pathlib import Path
from urllib.parse import urlsplit

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SIZE = 10

def signature(file):
    with Image.open(file) as image:
        width, height = image.size
        art = image.convert("RGB").crop((
            round(width * .27), round(height * .08), round(width * .73), round(height * .48),
        ))
        return art.resize((SIZE, SIZE), Image.Resampling.BOX).tobytes()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--merge", action="store_true", help="Preserve existing summaries for source images absent from this directory")
    args = parser.parse_args()
    correspondence = json.loads((ROOT / "docs/card-correspondence.json").read_text(encoding="utf-8"))
    output = ROOT / "apps/web/rivals-card-fingerprints.js"
    summaries = {}
    if args.merge and output.exists():
        existing = output.read_text(encoding="utf-8")
        old_ids = json.loads(re.search(r'export const fingerprintIds = (.+)', existing).group(1))
        old_colors = b64decode(json.loads(re.search(r'export const fingerprintColors = (.+)', existing).group(1)))
        chunk = SIZE * SIZE * 3
        if len(old_colors) != len(old_ids) * chunk:
            raise ValueError("Unexpected existing fingerprint size")
        summaries = {card_id: old_colors[index * chunk:(index + 1) * chunk] for index, card_id in enumerate(old_ids)}
    missing = []
    for record in correspondence["cards"]:
        if record["implementation"] != "tested":
            continue
        url = record.get("archive", {}).get("cardImageUrl") or record["referenceUrl"]
        path = urlsplit(url)
        filename = Path(path.path).name if path.netloc == "dqrdb.com" and path.path.startswith("/card/") else record["ftId"] + ".jpg"
        image = args.archive / filename
        if not image.is_file():
            missing.append(record["ftId"])
            continue
        summaries[record["ftId"]] = signature(image)
    ids = list(summaries)
    samples = b"".join(summaries.values())
    if not ids:
        raise ValueError("No source images were found in the specified directory.")
    output.write_text(
        "// Generated by scripts/build-rivals-fingerprints.py from the DQRDB catalog and supplementary card references.\n"
        + f"export const gridSize = {SIZE}\n"
        + "export const fingerprintIds = " + json.dumps(ids, separators=(",", ":")) + "\n"
        + "export const fingerprintColors = " + json.dumps(b64encode(samples).decode("ascii")) + "\n",
        encoding="utf-8",
    )
    print(f"{len(ids)} matched cards. Missing references: {', '.join(missing)}")

if __name__ == "__main__":
    main()

